def station(k,name='',sino=False):
    # 이름의 가타카나 구간은 표기 사전으로, 나머지는 읽기 규칙으로 옮긴다
    nm=re.sub(r'[（(].*?[)）]','',name)
    raw=re.sub(r'[（(].*?[)）]','',k)
    if nm.strip()+'|'+raw in NW:return NW[nm.strip()+'|'+raw][0]
    k=hira(raw)
    for j,h,r in MORPH:
        if j in nm and h in k:
            a,b=k.split(h,1);c=nm.split(j,1)
            return (station(a,c[0]) if a else '')+r+(conv(b,c[1]) if b else '')
    for j,h,r in (SINO if sino else ()):
        if j in nm and h in k:
            a,b=k.split(h,1);c=nm.split(j,1)
            left=station(a,c[0],True) if a else ''
            right=station(b,c[1],True) if b else ''
            # 지명과 한자어 사이는 띄어 쓴다 (카시마 임항선, 도야마 지방철도 사사즈선). 한자어끼리는 붙인다
            gap=' ' if left and not any(c[0].endswith(x) for x,_,_ in SINO) else ''
            gap2=' ' if right and (j=='鉄道' or not any(c[1].startswith(x) for x,_,_ in SINO)) else ''
            return left+gap+r+gap2+right
    if nm.endswith('港') and k.endswith('こう') and len(nm)>1:
        return station(k[:-2],nm[:-1])+'항'
    for j_,h_,r_ in PLACE:
        if nm.startswith(j_) and k.startswith(h_) and len(nm)>len(j_):
            return r_+station(k[len(h_):],nm[len(j_):])
    if '空港' in nm and 'くうこう' in k:
        a,b=k.split('くうこう',1);c=nm.split('空港',1)
        return (station(a,c[0]) if a else '')+'공항'+(station(b,c[1]) if b else '')
    prefix=''
    if nm.startswith('JR') and k.startswith('じぇいあーる'):
        prefix='JR ';k=k[len('じぇいあーる'):];nm=nm[2:]
    parts=[];rest=k
    for tok in sorted(re.findall('[ァ-ヺー]{2,}',nm),key=nm.find):
        h=hira(tok)
        if tok in LOAN and h in rest:
            a,rest=rest.split(h,1)
            if a:parts.append(conv(a,nm))
            parts.append(LOAN[tok])
    if parts:
        if rest:parts.append(conv(rest,nm))
        return prefix+''.join(parts)
    r=conv(rest,nm)
    if prefix:return prefix+r
    if nm in ('東京','京都','神戸') and r in FIX:r=FIX[r]
    for a,b in (('토카이도','도카이도'),('토호쿠','도호쿠'),('큐슈','규슈')):
        if r.startswith(a):r=b+r[len(a):]
    return r
def line(k,name=''):
    k=re.sub(r'[（(].*?[)）]','',k)
    k=re.sub(r'^じぇ[いえ]?あーる','',k)
    suf=''
    for a,b in (('しんかんせん',' 신칸센'),('ほんせん',' 본선'),('しせん',' 지선'),('せん','선')):
        if a=='しせん' and not re.sub(r'[（(].*?[)）]','',name).endswith('支線'):continue
