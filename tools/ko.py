def conv(k,name=''):
    k=hira(k)
    k=re.sub(r'[（(].*?[)）]','',k)
    k=re.sub(r'[^ぁ-ゖ]','',k)
    if '飯' in name:k=re.sub('いい(?=.)','い',k,1)
    if 'にい' in k and '新' in name and not re.search('新[居井町]',name):k=k.replace('にい','に',1)
    keep=set()
    for m,c in UMORPH+(('うら','のうら'),('うし','うしく')):
        if c in name and '河内' not in name:
            for x in re.finditer(m,k):
                if x.start()==0 or k[x.start()-1] not in 'ょゅ':keep.add(x.start())
    o=[];i=0;last=None;dropped=False
    while i<len(k):
        two=k[i:i+2]
        if two in Y:
            o.append(Y[two]);last=two[1];i+=2;dropped=False;continue
        c=k[i]
        if c=='ん':
            if o:o[-1]=jong(o[-1],4)
            i+=1;last='ん';dropped=False;continue
        if c=='っ':
            if o:o[-1]=jong(o[-1],19)
            i+=1;last='っ';dropped=False;continue
        v=vowel_of(last) if last else None
        nxt=k[i+1:i+2]
        lng=(c=='う' and v in('o','u') and i not in keep and nxt!='ん') or (c=='お' and nxt!='ん' and '尾' not in name and (last in('お','と','こ','ほ','ょ') or (last=='ど' and nxt in('り','し')) or (last=='ご' and nxt=='り')))
        if lng and not dropped:
            i+=1;dropped=True;continue
        dropped=False
        if c in T:
            o.append(T[c]);last=c
        i+=1
    return ''.join(o)
